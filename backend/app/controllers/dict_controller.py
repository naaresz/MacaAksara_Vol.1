def suggest_corrected_word(word: str) -> str:
    word = word.lower().strip()
    if not word:
        return word
        
    # If it's already a valid dictionary word, return it as is
    if lookup_word(word):
        return word
        
    # Check for basic Javanese prefixes/suffixes
    prefix = ""
    suffix = ""
    base_word = word
    
    if word.startswith("di") and len(word) > 4:
        prefix = "di"
        base_word = word[2:]
    elif word.endswith("ne") and len(word) > 4:
        suffix = "ne"
        base_word = word[:-2]
        
    # If base word is valid, return
    if lookup_word(base_word):
        return word
        
    # Find all known vocabulary words to match against
    all_vocab = list(JAVANESE_TO_INDONESIAN.keys())
    try:
        from sqlmodel import Session, select
        from backend.app.models.database import engine, Dictionary
        with Session(engine) as session:
            db_words = session.exec(select(Dictionary.word)).all()
            all_vocab.extend(db_words)
    except Exception:
        pass
    all_vocab = list(set(all_vocab))
    
    best_match = base_word
    min_dist = float('inf')
    best_score = -1
    
    for vocab_word in all_vocab:
        # Only evaluate words of similar length to prevent garbage mappings
        if abs(len(vocab_word) - len(base_word)) <= 2:
            dist = levenshtein_distance(base_word, vocab_word)
            # Max allowed distance is 2 edits to prevent garbage mappings
            max_allowed = 2
            if dist <= max_allowed:
                # Calculate prefix overlap (consecutive characters from start)
                prefix_len = 0
                for char1, char2 in zip(base_word, vocab_word):
                    if char1 == char2:
                        prefix_len += 1
                    else:
                        break
                # Simple letter overlap count
                overlap = sum(1 for c in base_word if c in vocab_word)
                score = prefix_len * 2 + overlap
                
                if dist < min_dist:
                    min_dist = dist
                    best_match = vocab_word
                    best_score = score
                elif dist == min_dist:
                    # Tie-breaker: prefer higher prefix alignment sarta overlap score
                    if score > best_score:
                        best_score = score
                        best_match = vocab_word
                
    return prefix + best_match + suffix

def translate_javanese_to_indonesian(latin_text):
    """
    Translates Latin Javanese text into Indonesian by split-matching words line-by-line.
    """
    if not latin_text:
        return "Tidak ada teks untuk diterjemahkan."
        
    lines = latin_text.split("\n")
    translated_lines = []
    
    for line in lines:
        if not line.strip():
            translated_lines.append("")
            continue
            
        words = line.lower().strip().split()
        translated_words = []
        
        for word in words:
            # 1. Spelling correction layer
            corrected = suggest_corrected_word(word)
            
            # 2. Direct lookup (DB first, then local dictionary)
            translation = lookup_word(corrected)
            if translation:
                translated_words.append(translation)
            # Try to strip basic Javanese prefixes/suffixes if not found
            elif corrected.endswith("ne"):
                base_trans = lookup_word(corrected[:-2])
                if base_trans:
                    translated_words.append(f"{base_trans}-nya")
                else:
                    translated_words.append(f"[{corrected}]")
            elif corrected.startswith("di"):
                base_trans = lookup_word(corrected[2:])
                if base_trans:
                    translated_words.append(f"di-{base_trans}")
                else:
                    translated_words.append(f"[{corrected}]")
            else:
                translated_words.append(f"[{corrected}]") # Keep untranslated words in brackets
        translated_lines.append(" ".join(translated_words))
            
    return "\n".join(translated_lines)

